const messages = { en, 'zh-CN': zhCN }
export const legacyLocaleStorageKey = 'craft-hub-locale'

function detectLocale(): Locale {
  return window.navigator.language.toLowerCase().startsWith('zh') ? 'zh-CN' : 'en'
}

const useI18nStore = defineStore('i18n', () => {
  const locale = ref<Locale>(detectLocale())
  document.documentElement.lang = locale.value

  function setLocale(value: Locale): void {
    locale.value = value
    document.documentElement.lang = value
  }

  function t(key: MessageKey, params: Record<string, string> = {}): string {
    return Object.entries(params).reduce(
      (message, [name, value]) => message.replaceAll(`{${name}}`, value),
      messages[locale.value][key] as string,
    )
  }

  return { locale, setLocale, t }
})
const fallbackPinia = createPinia()

if (import.meta.hot)
  import.meta.hot.accept(acceptHMRUpdate(useI18nStore, import.meta.hot))

/** Return the shared, HMR-stable workbench localization state. */
export function useI18n(): I18n {
  const store = useI18nStore(getActivePinia() ?? fallbackPinia)
  const { locale } = storeToRefs(store)
  return {
    locale,
    setLocale: value => store.setLocale(value),
    t: (key, params) => store.t(key, params),
  }
}
